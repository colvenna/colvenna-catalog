"""The matrix page (Markdown) from one run's results, or several runs' (one per form): what was
declared, what happened, and why for every limitation and failure. Generated, never edited by hand:
`tests/compat/matrix.py page <run dir>...`."""

import hashlib
import json
from pathlib import Path

from . import config
from .config import OPERATIONS, TABLE_TYPES

TABLE_NAMES = {"pk": "primary key", "pk-dv": "primary key, deletion vectors", "append": "append"}
OP_NAMES = {"ddl": "Create, drop", "write": "Write, commit", "read": "Read",
            "credentials": "Per-table credentials", "endpoints": "Endpoints"}
FORM_NAMES = {"eks": "EKS", "serverless": "serverless"}
STATUS = {"PASS": "pass", "FAIL": "**FAIL**", "NOT_RUN": "not run"}

HOW = """\
How each operation is checked (tests/compat/README.md has the details):

- **Create, drop**: the engine creates a database and the table in its SQL, lists them, drops the
  table and the database, and lists them again.
- **Write, commit**: inserts ids 1..100, writes ids 91..110 again (an upsert on a primary-key table,
  twenty more rows on an append table) and, on primary-key tables, deletes ids 1..5; each write is a
  commit, and the catalog's access log must show at least that many commits on the table. The
  deletion-vector table also gets ids 111..120 with `write-only` set, left uncompacted in level 0
  as between a streaming writer's compactions, and must hold deletion vectors and level-0 files
  afterwards.
- **Read**: row count, sum and point reads give exactly what the writes leave; on the
  deletion-vector table (`deletion-vectors.merge-on-read`), that includes the uncompacted rows.
- **Per-table credentials**: the engine runs with `data-token.enabled=true` and no S3 keys of its
  own; its own identity (pod or host) is refused the table's files, yet it wrote and read them, and
  the catalog's access log shows it was issued the table's credentials.
- **Endpoints**: in the catalog's access log, none of the engine's requests went to an endpoint the
  catalog does not serve (no route, or 501 other than the partition listing it declines by design).
"""


def load(run_dir):
    run_dir = Path(run_dir)
    meta = json.loads((run_dir / "run.json").read_text())
    cells = [json.loads(p.read_text()) for p in sorted((run_dir / "cells").glob("*.json"))]
    order = {c: i for i, c in enumerate(meta["cells"])}
    cells.sort(key=lambda c: order.get(c["cell"], 99))
    return meta, cells


def writer_name(cell_id):
    """A writer cell as the page names it: Flink 1.20.5 with Paimon 2.1.0."""
    try:
        cell = config.cell_by_id(config.load_cells(), cell_id)
        return f"{cell['engine']} {cell['engineVersion']} with Paimon {cell['paimon']}"
    except (KeyError, OSError, config.ConfigError):
        return cell_id


def entry(v, notes):
    text = STATUS[v["status"]]
    if v["declared"] == "limitation":
        n = notes.setdefault(v["reason"], len(notes) + 1)
        text = f"limitation [{n}]: {text}"
    return text


def current_reasons(declared, form, cell):
    """Each limitation's reason as declared.tsv gives it now: what was declared before a run
    stays, and its reason may since say what the runs measured."""
    for table in TABLE_TYPES:
        for op in OPERATIONS:
            value = declared.get((form, cell["cell"], table, op))
            v = cell["results"][table][op]
            if value and value[0] == v["declared"] == "limitation" and value[1]:
                v["reason"] = value[1]


def render(run_dirs, link_base=None, declared=None):
    """The page; declared: declared.tsv's declarations ({} to keep each run's own reasons)."""
    declared_digest = None
    if declared is None:
        declared = config.load_declarations(config.load_cells())
        declared_digest = hashlib.sha256(config.DECLARED_FILE.read_bytes()).hexdigest()
    out = ["# Colvenna Catalog compatibility matrix", ""]
    out.append("Generated by `tests/compat/matrix.py page` from the results of the runs below; each cell is "
               "an engine version and the Paimon client it runs, against Colvenna Catalog in one deployment "
               "form. Before a run every cell is declared, down to table type and operation, either supported, "
               "which must pass, or a known limitation of the engine (`tests/compat/declared.tsv`). Every "
               "verdict comes from that run, whose raw output is kept beside it.")
    out.append("")
    for run_dir in run_dirs:
        meta, cells = load(run_dir)
        for cell in cells:
            current_reasons(declared, meta["form"], cell)
        notes = {}
        form = FORM_NAMES.get(meta["form"], meta["form"])
        raw = f"{link_base}/{Path(run_dir).name}" if link_base else str(run_dir)
        backend = "Kubernetes pods" if meta["backend"] == "kubernetes" else "Docker containers"
        out += [f"## {form} form, engines as {backend}: run {meta['run']}", ""]
        facts = [f"Started {meta['started'][:16].replace('T', ' ')} UTC"]
        if meta.get("fixture"):
            facts.append(f"the readers read tables written by {writer_name(meta['fixture']['writer'])}")
        if meta.get("engineIdentity"):
            facts.append(f"the engines ran as {meta['engineIdentity']}")
        if meta.get("region"):
            facts.append(f"region {meta['region']}")
        if meta.get("catalog"):
            facts.append(f"catalog {meta['catalog']}")
        if meta.get("matrixCommit"):
            facts.append(f"matrix at `{meta['matrixCommit'][:12]}`" + (" (uncommitted changes)" if meta.get(
                "matrixTreeDirty") else ""))
        out += ["; ".join(facts) + f". Raw results: [{Path(run_dir).name}]({raw}/).", ""]
        if declared_digest and meta.get("declaredSha256") and meta["declaredSha256"] != declared_digest:
            same = all(declared.get((meta["form"], c["cell"], t, o), ("",))[0] == c["results"][t][o]["declared"]
                       for c in cells for t in TABLE_TYPES for o in OPERATIONS)
            out += [("`declared.tsv` has changed since this run: the same declarations, their reasons now the causes "
                     "the runs measured." if same else "**`declared.tsv`'s declarations have changed since this run.**"), ""]
        again = sorted({(c["rejudged"]["matrixCommit"] or "")[:12] for c in cells if c.get("rejudged")})
        changes = [f"{c['engine']} {c['engineVersion']} {x}" for c in cells for x in c.get("rejudged", {}).get("changed", [])]
        if again:
            out += [f"Judged again from the run's kept raw output by `matrix.py rejudge` at `{', '.join(again)}`"
                    + (f": {'; '.join(changes)}." if changes else ", with no verdict changed."), ""]
        if meta.get("completed") is False:
            out += ["**This run was stopped before it ended**: only the cells below ran.", ""]
        missing = [c for c in meta["cells"] if c not in {cell["cell"] for cell in cells}]
        if missing:
            out += [f"**No result** for {', '.join(missing)}: the run ended before them.", ""]

        out += ["| Engine | Paimon client | Declared supported, passed | Known limitations | Outcome |",
                "| --- | --- | --- | --- | --- |"]
        for c in cells:
            entries = [c["results"][t][o] for t in TABLE_TYPES for o in OPERATIONS]
            supported = [e for e in entries if e["declared"] == "supported"]
            passed = [e for e in supported if e["status"] == "PASS"]
            limited = len(entries) - len(supported)
            out.append(f"| {c['engine']} {c['engineVersion']} | {c['paimon']} | {len(passed)} of {len(supported)} | "
                       f"{limited} | {'pass' if c['outcome'] == 'pass' else '**fail**'} |")
        out.append("")

        out += ["| Engine | Paimon client | Table | " + " | ".join(OP_NAMES[o] for o in OPERATIONS) + " |",
                "| --- | --- | --- | " + " | ".join("---" for _ in OPERATIONS) + " |"]
        for c in cells:
            for t in TABLE_TYPES:
                row = [f"{c['engine']} {c['engineVersion']}", c["paimon"], TABLE_NAMES[t]]
                row += [entry(c["results"][t][o], notes) for o in OPERATIONS]
                out.append("| " + " | ".join(row) + " |")
        out.append("")

        if notes:
            out += ["Known limitations, declared before the run, with the causes the runs measured "
                    "(`tests/compat/declared.tsv`):", ""]
            for reason, n in sorted(notes.items(), key=lambda kv: kv[1]):
                out.append(f"{n}. {reason[0].upper() + reason[1:]}.")
            out.append("")
            seen = []
            for c in cells:
                for t in TABLE_TYPES:
                    for o in OPERATIONS:
                        v = c["results"][t][o]
                        if v["declared"] == "limitation" and not v["detail"].startswith("read-only engine"):
                            seen.append(f"- {c['engine']} {c['engineVersion']}, {TABLE_NAMES[t]}, "
                                        f"{OP_NAMES[o].lower()}: {STATUS[v['status']]}: {v['detail']}")
            if seen:
                out += ["What the run saw where a limitation is declared:", ""] + seen + [""]

        failures = [f"- {c['engine']} {c['engineVersion']} with Paimon {c['paimon']}, {TABLE_NAMES[t]}, "
                    f"{OP_NAMES[o].lower()}: {c['results'][t][o]['detail']}"
                    for c in cells for t in TABLE_TYPES for o in OPERATIONS
                    if c["results"][t][o]["declared"] == "supported" and c["results"][t][o]["status"] != "PASS"]
        if failures:
            out += ["Declared supported but not passed:", ""] + failures + [""]
        cleanup = meta.get("cleanup", {})
        if cleanup.get("status") == "PASS":
            dropped = ", ".join(cleanup.get("dropped", [])) or "none was left to drop"
            out += [f"Clean-up: no database of the run is left ({dropped}).", ""]
        else:
            why = cleanup.get("detail") or f"left {', '.join(cleanup.get('remaining', []))}"
            out += [f"Clean-up: **FAILED**: {why}.", ""]
    out += [HOW]
    return "\n".join(out).rstrip() + "\n"
